test('symbolic links and junctions are rejected at every level', async (t) => {
  const redirects = {
    'the references directory': ['references', 'references'],
    'the reference directory': [`references/${referenceId}`, 'reference'],
    'the qualification directory': [`references/${referenceId}/qualification`, 'qualification'],
    'the crate directory': [crate, 'crate'],
    'the src directory': [`${crate}/src`, 'src'],
  };
  for (const [name, [relative, destination]] of Object.entries(redirects)) {
    await t.test(`${name} redirected outside the checkout`, (subtest) => {
      let created = true;
      const errors = run((c) => {
        // Move the real directory out and leave a link at the original name, so
        // the redirected tree still holds a complete, valid crate.
        const moved = join(c.outside, destination);
        renameSync(c.path(relative), moved);
        created = c.link(moved, relative);
        if (!created) renameSync(moved, c.path(relative));
      });
      if (!created) return subtest.skip('this account cannot create symbolic links or junctions');
      assertRejected(errors, /symbolic link or junction/);
    });
  }
  for (const file of ['Cargo.toml', 'Cargo.lock', 'README.md', 'src/lib.rs']) {
    await t.test(`${file} is a file symlink`, (subtest) => {
      let created = true;
      const errors = run((c) => {
        const real = join(c.outside, 'real-file');
        put(real, 'content\n');
        rmSync(c.path(`${crate}/${file}`));
        created = c.fileLink(real, `${crate}/${file}`);
      });
      if (!created) return subtest.skip('this account cannot create file symbolic links');
      assertRejected(errors, /symbolic link or junction/);
    });
  }
  await t.test('a link nested inside the crate tree', (subtest) => {
    let created = true;
    const errors = run((c) => {
      mkdirSync(join(c.outside, 'vendor'), { recursive: true });
      created = c.link(join(c.outside, 'vendor'), `${crate}/src/vendor`);
    });
    if (!created) return subtest.skip('this account cannot create symbolic links or junctions');
    assertRejected(errors, /src\/vendor is a symbolic link or junction/);
  });
  await t.test('a link named target is not skipped like a real build directory', (subtest) => {
    let created = true;
    const errors = run((c) => {
      mkdirSync(join(c.outside, 'target'), { recursive: true });
      created = c.link(join(c.outside, 'target'), `${crate}/target`);
    });
    if (!created) return subtest.skip('this account cannot create symbolic links or junctions');
    assertRejected(errors, /target is a symbolic link or junction/);
  });
});

