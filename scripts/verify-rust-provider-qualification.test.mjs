function put(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

function writeCrate(directory) {
  put(join(directory, 'Cargo.toml'), cargoToml);
  put(join(directory, 'Cargo.lock'), cargoLock);
  put(join(directory, 'README.md'), '# Rust v3 conformance guest\n');
  put(join(directory, 'src', 'lib.rs'), libRs);
}

function writeWit(directory) {
  for (const [name, content] of Object.entries(witFiles)) put(join(directory, ...name.split('/')), content);
}

// `authorProjects` adds the four advertised language projects; `repository` adds
// the index, support matrix and shared files that verify-references.mjs needs.
function createFixture({ authorProjects = false, repository = false } = {}) {
  const base = mkdtempSync(join(tmpdir(), 'glixo-rust-qualification-'));
  const root = join(base, 'checkout');
  const outside = join(base, 'outside');
  const links = [];
  const context = {
    base, root, outside, links,
    item: {
      id: referenceId, kind: 'executable', status: 'preview', languages: [...languages],
      contract: `${providerWorld} + glixo:http/broker@3.0.0`, hostAcceptance: 'pending',
      qualification: qualificationDeclaration(),
      scaffold: {
        sourcePath: `references/${referenceId}/{language}`,
        manifestPath: `references/${referenceId}/{language}/glixo.extension.json`,
        projectManifestPath: `references/${referenceId}/{language}/glixo.project.json`,
        sharedPaths: [],
        substitutions: { '{{PACKAGE_ID}}': 'package.id', '{{NAME}}': 'package.name', '{{PUBLISHER}}': 'package.publisher' },
      },
    },
    support: supportMatrix(),
    path: (relative) => join(root, ...relative.split('/')),
    read: (relative) => readFileSync(join(root, ...relative.split('/')), 'utf8'),
    replace(relative, from, to) {
      const text = context.read(relative);
      assert.ok(text.includes(from), `fixture drifted: ${relative} does not contain ${from}`);
      put(context.path(relative), text.replace(from, to));
    },
    // Directory redirect. Junctions need no privilege on Windows; POSIX uses a plain symlink.
    link(target, relative) {
      try {
        symlinkSync(target, context.path(relative), process.platform === 'win32' ? 'junction' : 'dir');
      } catch (error) {
        if (['EPERM', 'EACCES'].includes(error.code)) return false;
        throw error;
      }
      links.push(context.path(relative));
      return true;
    },
    fileLink(target, relative) {
      try {
        symlinkSync(target, context.path(relative), 'file');
      } catch (error) {
        if (['EPERM', 'EACCES'].includes(error.code)) return false;
        throw error;
      }
      links.push(context.path(relative));
      return true;
    },
    syncRepository() {
      put(context.path('references/reference-index.json'), JSON.stringify({ schemaVersion: 1, references: [context.item] }));
      put(context.path('packages/extension-sdk/support-matrix.json'), JSON.stringify(context.support));
    },
    cleanup() {
      for (const link of links) {
        try { unlinkSync(link); } catch { try { rmdirSync(link); } catch { /* already gone */ } }
      }
      rmSync(base, { recursive: true, force: true });
    },
  };
  mkdirSync(outside, { recursive: true });
  writeCrate(context.path(crate));
  writeWit(context.path(`references/${referenceId}/rust/wit`));
  put(context.path('packages/extension-sdk/rust/Cargo.toml'), '[package]\nname = "glixo-extension-sdk"\nversion = "0.1.0"\n');
  put(context.path('packages/extension-sdk/rust/src/lib.rs'), 'pub mod guest;\n');
  if (authorProjects) writeAuthorProjects(context);
  if (repository) {
    put(context.path('references/_shared/README.md'), '# Shared\n');
    context.syncRepository();
  }
  return context;
}

function writeAuthorProjects(context) {
  for (const language of languages) {
    const project = `references/${referenceId}/${language}`;
    const recipeId = `ollama-provider-${language}-v3`;
    put(context.path(`${project}/README.md`), `# ${language}\n\nToolchain availability is not host or release qualification.\n`);
    put(context.path(`${project}/reference.json`), JSON.stringify({ referenceId, language, build: { recipeId }, placeholder: false }));
    put(context.path(`${project}/glixo.project.json`), JSON.stringify({ components: [{ recipe: recipeId }] }));
    put(context.path(`${project}/glixo.extension.json`), JSON.stringify({ description: 'Toolchain availability is not host or release qualification.' }));
    for (const [name, content] of Object.entries(buildFiles[language])) put(context.path(`${project}/${name}`), content);
  }
}

function run(mutate = () => {}, options = {}) {
  const context = createFixture(options);
  try {
    mutate(context);
    return verifyRustProviderQualification({ root: context.root, item: context.item, support: context.support });
  } finally {
    context.cleanup();
  }
}

function runReferences(mutate = () => {}) {
  const context = createFixture({ authorProjects: true, repository: true });
  try {
    mutate(context);
    context.syncRepository();
    const result = spawnSync(process.execPath, [referencesScript], { cwd: context.root, encoding: 'utf8', shell: false });
    return { status: result.status, output: `${result.stdout}\n${result.stderr}` };
  } finally {
    context.cleanup();
  }
}

function assertRejected(errors, pattern, message = 'expected a rejection') {
  assert.ok(errors.some((error) => pattern.test(error)), `${message}: ${pattern}\nactual:\n${errors.join('\n') || '(no errors)'}`);
}

function moveCaseOnly(context, from, to) {
  renameSync(context.path(from), context.path(`${from}.moving`));
  renameSync(context.path(`${from}.moving`), context.path(to));
}

